const byVariant = new Map();
const byCanonical = new Map();

for (const { name, variants } of nameVariants) {
  const n = normalize(name);
  if (!n) continue;
  const set = new Set([n]);
  for (const v of variants) {
    const vn = normalize(v);
    if (vn) set.add(vn);
  }
  byCanonical.set(n, set);
  for (const x of set) {
    if (!byVariant.has(x)) byVariant.set(x, []);
    byVariant.get(x).push(n);
  }
}

export const expandNameForms = (q) => {
  const n = normalize(q);
  if (!n) return [];
  const result = new Set([n]);
  const canonicals = byVariant.get(n) || [];
  for (const c of canonicals) {
    const set = byCanonical.get(c);
    if (set) set.forEach((x) => result.add(x));
  }
  return Array.from(result);
};